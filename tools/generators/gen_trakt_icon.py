#!/usr/bin/env python3
"""Deterministic pixel-art icon for Trakt (replaces the ARR upstream logo).

Concept: a T-junction post road ("trakt" = a country/post highway) on a warm
dark background — chunky 16x16 logical grid scaled to 128x128.

Provenance: generated by this script (no upstream pixels); recorded in
THIRD_PARTY_ASSETS.md. Re-run: python3 scripts/gen_trakt_icon.py
"""
from PIL import Image, ImageDraw

SCALE = 8
GRID = 16
SIZE = GRID * SCALE  # 128

# palette (ours)
BG = (46, 40, 32, 255)          # dark warm soil
BG_EDGE = (34, 30, 24, 255)     # vignette border
ROAD = (198, 158, 90, 255)      # ochre dirt road
ROAD_EDGE = (122, 92, 52, 255)  # darker rim
DASH = (239, 227, 192, 255)     # cream centreline
COIN = (232, 180, 74, 255)      # waycoin gold accent
COIN_EDGE = (150, 108, 34, 255)

img = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
draw = ImageDraw.Draw(img)


def cell(x, y, color):
    draw.rectangle([x * SCALE, y * SCALE, (x + 1) * SCALE - 1, (y + 1) * SCALE - 1], fill=color)


def band(x0, y0, x1, y1, fill, edge):
    """Filled band with 1-cell edge frame."""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            on_edge = x in (x0, x1) or y in (y0, y1)
            cell(x, y, edge if on_edge else fill)


# background rounded-ish square with vignette
for y in range(GRID):
    for x in range(GRID):
        corner = (x in (0, 15) and y in (0, 15)) or (x in (1, 14) and y in (0, 15)) or (x in (0, 15) and y in (1, 14))
        if x in (0, 15) and y in (0, 15):
            continue  # cut corners
        cell(x, y, BG_EDGE if (x in (0, 15) or y in (0, 15)) else BG)

# T-junction road: horizontal arm across upper third, vertical stem to the bottom
band(1, 4, 14, 8, ROAD, ROAD_EDGE)   # horizontal road (west-east)
band(6, 8, 9, 14, ROAD, ROAD_EDGE)   # vertical stem (south)

# cream centreline dashes
for x in (2, 4, 6, 8, 10, 12, 14 - 1):
    cell(x, 6, DASH)
cell(7, 10, DASH)
cell(7, 13, DASH)

# waycoin marker at the junction (3x3 coin with darker rim)
for dy, row in enumerate((0, 1, 2)):
    for dx in range(3):
        on_edge = dx in (0, 2) or dy in (0, 2)
        cell(10 + dx, 2 + dy, COIN_EDGE if on_edge else COIN)

OUT = __import__('pathlib').Path(__file__).resolve().parents[2] / 'src/main/resources/assets/trakt/icon.png'
img.save(OUT, 'PNG')
print('written', OUT, img.size)
